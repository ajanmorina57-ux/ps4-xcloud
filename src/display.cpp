DisplayEngine::DisplayEngine(int width, int height)
    : m_width(width), m_height(height) {}

DisplayEngine::~DisplayEngine() {
    shutdown();
}

bool DisplayEngine::init() {
#if defined(__ORBIS__) || defined(__PS4__)
    if (m_initialized) return true;

    m_videoHandle = sceVideoOutOpen(ORBIS_VIDEO_USER_MAIN, ORBIS_VIDEO_OUT_BUS_MAIN, 0, 0);
    if (m_videoHandle < 0) {
        printf("[Display] Failed to open video out handle\n");
        return false;
    }

    int rc = sceKernelCreateEqueue(&m_flipQueue, "xcloud_flip_queue");
    if (rc < 0) {
        printf("[Display] Failed to create flip event queue: 0x%08X\n", rc);
        shutdown();
        return false;
    }
    m_flipQueueCreated = true;
    rc = sceVideoOutAddFlipEvent(m_flipQueue, m_videoHandle, nullptr);
    if (rc < 0) {
        printf("[Display] Failed to register flip event: 0x%08X\n", rc);
        shutdown();
        return false;
    }

    // Allocate 1920x1080x4 bytes per buffer * 2 buffers
    size_t frameSize = m_width * m_height * m_depth;
    size_t totalMem = frameSize * 2;
    int alignment = 0x200000; // 2MB alignment for PS4 GPU
    size_t directMemSize = (totalMem + alignment - 1) / alignment * alignment;

    rc = sceKernelAllocateDirectMemory(0, sceKernelGetDirectMemorySize(), directMemSize, alignment, 3, &m_directMemOff);
    if (rc < 0) {
        printf("[Display] Failed to allocate direct video memory: 0x%08X\n", rc);
        shutdown();
        return false;
    }
    m_directMemSize = directMemSize;

    rc = sceKernelMapDirectMemory(&m_videoMem, m_directMemSize, 0x33, 0, m_directMemOff, alignment);
    if (rc < 0) {
        printf("[Display] Failed to map direct video memory: 0x%08X\n", rc);
        shutdown();
        return false;
    }

    m_buffers[0] = (uint8_t*)m_videoMem;
    m_buffers[1] = (uint8_t*)m_videoMem + frameSize;

    OrbisVideoOutBufferAttribute attr;
    sceVideoOutSetBufferAttribute(
        &attr,
        ORBIS_VIDEO_OUT_PIXEL_FORMAT_A8B8G8R8_SRGB,
        ORBIS_VIDEO_OUT_TILING_MODE_LINEAR,
        ORBIS_VIDEO_OUT_ASPECT_RATIO_16_9,
        m_width,
        m_height,
        m_width);
    rc = sceVideoOutRegisterBuffers(m_videoHandle, 0, (void**)m_buffers, 2, &attr);
    if (rc < 0) {
        printf("[Display] Failed to register video buffers: 0x%08X\n", rc);
        shutdown();
        return false;
    }
    m_buffersRegistered = true;

    rc = sceVideoOutSetFlipRate(m_videoHandle, 0); // VSync
    if (rc < 0) {
        printf("[Display] Failed to set flip rate: 0x%08X\n", rc);
        shutdown();
        return false;
    }
#endif
    m_initialized = true;
    return true;
}

void DisplayEngine::shutdown() {
#if defined(__ORBIS__) || defined(__PS4__)
    if (m_flipQueueCreated) {
        sceKernelDeleteEqueue(m_flipQueue);
        m_flipQueue = 0;
        m_flipQueueCreated = false;
    }
    if (m_buffersRegistered && m_videoHandle >= 0) {
        int rc = sceVideoOutUnregisterBuffers(m_videoHandle, 0);
        if (rc < 0) {
            printf("[Display] Failed to unregister video buffers: 0x%08X\n", rc);
        }
        m_buffersRegistered = false;
    }
    if (m_videoHandle >= 0) {
        sceVideoOutClose(m_videoHandle);
        m_videoHandle = -1;
    }
    if (m_videoMem) {
        m_videoMem = nullptr;
    }
    if (m_directMemSize > 0) {
        sceKernelReleaseDirectMemory(m_directMemOff, m_directMemSize);
        m_directMemSize = 0;
    }
    m_buffers[0] = nullptr;
    m_buffers[1] = nullptr;
#endif
    m_initialized = false;
}

void DisplayEngine::clear(PixelColor color) {
    if (!m_initialized) return;
    uint32_t val = (static_cast<uint32_t>(color.a) << 24) |
                   (static_cast<uint32_t>(color.b) << 16) |
                   (static_cast<uint32_t>(color.g) << 8) |
                   static_cast<uint32_t>(color.r);
    uint32_t* dst = (uint32_t*)m_buffers[m_currentBuffer];
    size_t totalPixels = m_width * m_height;
    for (size_t i = 0; i < totalPixels; i++) {
        dst[i] = val;
    }
}

void DisplayEngine::fillRect(int x, int y, int w, int h, PixelColor color) {
    if (!m_initialized) return;
    uint32_t val = (static_cast<uint32_t>(color.a) << 24) |
                   (static_cast<uint32_t>(color.b) << 16) |
                   (static_cast<uint32_t>(color.g) << 8) |
                   static_cast<uint32_t>(color.r);
    uint32_t* base = (uint32_t*)m_buffers[m_currentBuffer];

    int xEnd = (x + w > m_width) ? m_width : x + w;
    int yEnd = (y + h > m_height) ? m_height : y + h;
    if (x < 0) x = 0;
    if (y < 0) y = 0;

    for (int cy = y; cy < yEnd; ++cy) {
        uint32_t* row = base + (cy * m_width);
        for (int cx = x; cx < xEnd; ++cx) {
            row[cx] = val;
        }
    }
}

void DisplayEngine::drawBorder(int x, int y, int w, int h, int thickness, PixelColor color) {
    fillRect(x, y, w, thickness, color); // Top
    fillRect(x, y + h - thickness, w, thickness, color); // Bottom
    fillRect(x, y, thickness, h, color); // Left
    fillRect(x + w - thickness, y, thickness, h, color); // Right
}

bool DisplayEngine::drawRgbaFrame(
    const uint8_t* rgba,
    uint32_t frameWidth,
    uint32_t frameHeight,
    size_t frameStride,
    std::string& error) {
    if (!m_initialized || m_buffers[m_currentBuffer] == nullptr) {
        error = "Display is not initialized.";
        return false;
    }
    return renderRgbaFrame(
        rgba,
        frameWidth,
        frameHeight,
        frameStride,
        m_buffers[m_currentBuffer],
        static_cast<uint32_t>(m_width),
        static_cast<uint32_t>(m_height),
        static_cast<size_t>(m_width) * m_depth,
        error);
}

void DisplayEngine::drawChar(char c, int x, int y, int scale, PixelColor color) {
    if (c < 32 || c > 126) c = '?';
    const uint8_t* glyph = g_font8x8_basic[c - 32];
    for (int row = 0; row < 8; ++row) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if ((bits >> (7 - col)) & 1) {
                fillRect(x + col * scale, y + row * scale, scale, scale, color);
            }
        }
    }
}

void DisplayEngine::drawText(const std::string& text, int x, int y, int scale, PixelColor color) {
    int curX = x;
    int curY = y;
    for (char c : text) {
        if (c == '\n') {
            curX = x;
            curY += 10 * scale;
            continue;
        }
        drawChar(c, curX, curY, scale, color);
        curX += 9 * scale;
    }
}

void DisplayEngine::present() {
#if defined(__ORBIS__) || defined(__PS4__)
    if (!m_initialized) return;

    int rc = sceVideoOutSubmitFlip(m_videoHandle, m_currentBuffer, ORBIS_VIDEO_OUT_FLIP_VSYNC, m_frameId);
    if (rc < 0) {
        printf("[Display] Failed to submit frame flip: 0x%08X\n", rc);
        return;
    }

    // Wait for flip event
    OrbisKernelEvent evt;
    int count = 0;
    while (true) {
        rc = sceKernelWaitEqueue(m_flipQueue, &evt, 1, &count, nullptr);
        if (rc < 0) {
            printf("[Display] Failed waiting for frame flip: 0x%08X\n", rc);
            return;
        }
        if (count > 0) break;
    }

    m_currentBuffer = 1 - m_currentBuffer;
    m_frameId++;
#endif
}

